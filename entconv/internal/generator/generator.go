// Package generator renders entconv converter source from matched ent types
// and protobuf messages.
package generator

import (
	"bytes"
	"embed"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"strings"
	"sync"
	"text/template"

	"entgo.io/ent/entc/gen"
	"github.com/go-sphere/entc-extensions/entconv/internal/converter"
	"github.com/go-sphere/entc-extensions/entproto"
	"golang.org/x/tools/imports"
)

// templateSource caches the embedded template text to avoid repeated file I/O.
var (
	templateSource     string
	templateSourceOnce sync.Once
	templateSourceErr  error
)

// ProtoMessage represents a parsed proto message from .pb.go file.
type ProtoMessage struct {
	Name   string
	Fields []ProtoField
}

// ProtoField represents a field in a proto message.
type ProtoField struct {
	Name string
	Type string
}

// TypeInfo holds information about a type being processed.
type TypeInfo struct {
	MessageName string
	Message     *ProtoMessage
	Type        *gen.Type
}

// Generator handles code generation for Ent <-> Proto converters.
type Generator struct {
	EntPackage  string
	ConvPackage string
	// ProtoPackagePath is the import path for the proto package.
	ProtoPackagePath string
	// ProtoAlias is the alias used for the proto package in generated code.
	ProtoAlias string
	Types      []TypeInfo
	Adapter    *entproto.Adapter
	Graph      *gen.Graph
	// nodeIndex provides O(1) lookup for node names
	nodeIndex map[string]*gen.Type
	// typeIndex provides O(1) lookup for type info by name
	typeIndex map[string]*TypeInfo
}

// New creates a new Generator.
func New(entPackage, pkg, pkgPath, protoAlias string, types []TypeInfo, adapter *entproto.Adapter, graph *gen.Graph) *Generator {
	// Build index for O(1) node lookup
	nodeIndex := make(map[string]*gen.Type, len(graph.Nodes))
	for _, node := range graph.Nodes {
		nodeIndex[node.Name] = node
	}

	// Build index for O(1) type info lookup
	typeIndex := make(map[string]*TypeInfo, len(types))
	for i := range types {
		typeIndex[types[i].Type.Name] = &types[i]
	}

	return &Generator{
		EntPackage:       entPackage,
		ConvPackage:      pkg,
		ProtoPackagePath: pkgPath,
		ProtoAlias:       protoAlias,
		Types:            types,
		Adapter:          adapter,
		Graph:            graph,
		nodeIndex:        nodeIndex,
		typeIndex:        typeIndex,
	}
}

//go:embed template/*
var templates embed.FS

// getTemplate parses a template bound to the current generator's function map.
func (g *Generator) getTemplate(plan *importPlan) (*gen.Template, error) {
	templateSourceOnce.Do(func() {
		tmplContent, err := fs.ReadFile(templates, "template/converter.tmpl")
		if err != nil {
			templateSourceErr = fmt.Errorf("failed to read template: %w", err)
			return
		}
		templateSource = string(tmplContent)
	})

	if templateSourceErr != nil {
		return nil, templateSourceErr
	}

	tmpl, err := gen.NewTemplate("converter").
		Funcs(g.templateFuncs(plan)).
		Parse(templateSource)
	if err != nil {
		return nil, fmt.Errorf("failed to parse template: %w", err)
	}
	return tmpl, nil
}

// Generate produces the converter code and writes to the specified output path.
func (g *Generator) Generate(outputPath string) error {
	var buf bytes.Buffer
	if err := g.generateBody(&buf); err != nil {
		return err
	}

	return os.WriteFile(outputPath, buf.Bytes(), 0644)
}

// generatedHeader marks files owned by this generator. It is used to clean up
// stale converters for schemas that no longer exist without touching files the
// user (or another generator) owns.
const generatedHeader = "// Code generated by protoc-gen-entconv. DO NOT EDIT."

// GenerateAll generates separate converter files for each type in the output directory.
func (g *Generator) GenerateAll(outputDir string) error {
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		return fmt.Errorf("creating output directory: %w", err)
	}
	if err := removeStaleConverters(outputDir); err != nil {
		return err
	}

	for _, typeInfo := range g.Types {
		var buf bytes.Buffer
		if err := g.generateSingleType(&buf, typeInfo); err != nil {
			return fmt.Errorf("generating %s: %w", typeInfo.Type.Name, err)
		}

		formatted, err := format.Source(buf.Bytes())
		if err != nil {
			return fmt.Errorf("formatting %s: %w", typeInfo.Type.Name, err)
		}

		outputPath := fmt.Sprintf("%s/%s.go", outputDir, strings.ToLower(typeInfo.Type.Name))
		// Use goimports to clean up unused imports
		optimized, err := imports.Process(outputPath, formatted, nil)
		if err != nil {
			return fmt.Errorf("optimizing imports for %s: %w", typeInfo.Type.Name, err)
		}

		if err := os.WriteFile(outputPath, optimized, 0644); err != nil {
			return fmt.Errorf("writing %s: %w", typeInfo.Type.Name, err)
		}
	}

	return nil
}

// removeStaleConverters deletes previously generated converter files from
// outputDir. Only files carrying this generator's header are removed, so a
// renamed or deleted schema does not leave behind a converter that references
// the now-missing ent type and breaks the package build.
func removeStaleConverters(outputDir string) error {
	entries, err := os.ReadDir(outputDir)
	if err != nil {
		return fmt.Errorf("reading output directory: %w", err)
	}
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".go" {
			continue
		}
		path := filepath.Join(outputDir, entry.Name())
		content, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("reading generated file %q: %w", path, err)
		}
		if !bytes.HasPrefix(content, []byte(generatedHeader)) {
			continue
		}
		if err := os.Remove(path); err != nil {
			return fmt.Errorf("removing stale generated file %q: %w", path, err)
		}
	}
	return nil
}

// GenerateToWriter produces the converter code and writes to the provided io.Writer.
// This method outputs raw code suitable for further processing (formatting, goimports, etc.) by the caller.
func (g *Generator) GenerateToWriter(w io.Writer) error {
	return g.generateBody(w)
}

// generateSingleType generates converter code for a single type.
func (g *Generator) generateSingleType(w io.Writer, typeInfo TypeInfo) error {
	tempGen := &Generator{
		EntPackage:       g.EntPackage,
		ConvPackage:      g.ConvPackage,
		ProtoPackagePath: g.ProtoPackagePath,
		ProtoAlias:       g.ProtoAlias,
		Types:            []TypeInfo{typeInfo},
		Adapter:          g.Adapter,
		Graph:            g.Graph,
		nodeIndex:        g.nodeIndex,
		typeIndex:        g.typeIndex,
	}
	return tempGen.generateBody(w)
}

// generateBody generates the converter code body (with imports) to the writer.
func (g *Generator) generateBody(w io.Writer) error {
	plan, err := g.buildImportPlan()
	if err != nil {
		return err
	}

	tmpl, err := g.getTemplate(plan)
	if err != nil {
		return err
	}

	// Write header with imports
	if err := g.writeImportsFromPlan(w, plan); err != nil {
		return err
	}

	// Execute template
	if err := tmpl.Execute(w, g); err != nil {
		return fmt.Errorf("template execution failed: %w", err)
	}

	return nil
}

type importSpec struct {
	Alias string
	Path  string
}

type importPlan struct {
	specs       []importSpec
	used        map[string]struct{}
	byPath      map[string]string
	entAlias    string
	protoAlias  string
	enumAliases map[string]string
	localVars   map[string]map[string]string
}

func (p *importPlan) add(pkgPath, preferredAlias string, emitAlias bool) string {
	if pkgPath == "" {
		return ""
	}
	if alias, ok := p.byPath[pkgPath]; ok {
		return alias
	}
	base := sanitizePkgAlias(preferredAlias, pkgPath)
	alias := base
	for i := 2; ; i++ {
		if _, exists := p.used[alias]; !exists {
			break
		}
		alias = fmt.Sprintf("%s%d", base, i)
	}
	p.used[alias] = struct{}{}
	p.byPath[pkgPath] = alias
	specAlias := ""
	if emitAlias || alias != path.Base(pkgPath) {
		specAlias = alias
	}
	p.specs = append(p.specs, importSpec{Alias: specAlias, Path: pkgPath})
	return alias
}

func sanitizePkgAlias(preferred, pkgPath string) string {
	candidate := preferred
	if candidate == "" {
		candidate = path.Base(pkgPath)
	}
	var b strings.Builder
	for i, r := range candidate {
		isLetter := (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_'
		isDigit := r >= '0' && r <= '9'
		switch {
		case isLetter || (i > 0 && isDigit):
			b.WriteRune(r)
		case i == 0 && isDigit:
			b.WriteByte('_')
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	alias := b.String()
	if alias == "" || alias == "_" || token.Lookup(alias).IsKeyword() {
		return "pkg_" + alias
	}
	return alias
}

func (g *Generator) buildImportPlan() (*importPlan, error) {
	plan := &importPlan{
		used: map[string]struct{}{
			// Reserve parameter/result names used in generated ToProto*/ToEnt* functions.
			"e": {},
			"v": {},
		},
		byPath:      make(map[string]string),
		enumAliases: make(map[string]string),
		localVars:   make(map[string]map[string]string, len(g.Types)),
	}

	fieldMaps := make(map[string]entproto.FieldMap, len(g.Types))
	usesTime := false
	for _, t := range g.Types {
		fieldMap, err := g.Adapter.FieldMap(t.Type.Name)
		if err != nil {
			return nil, fmt.Errorf("resolving field map for %s while collecting imports: %w", t.Type.Name, err)
		}
		fieldMaps[t.Type.Name] = fieldMap
		for _, f := range fieldMap.Fields() {
			if f.EntField != nil && f.EntField.IsTime() {
				usesTime = true
			}
		}
	}

	if usesTime {
		plan.add("time", "time", false)
	}
	plan.entAlias = plan.add(g.EntPackage, "ent", true)
	if g.ProtoPackagePath != "" && g.ProtoAlias != "" {
		plan.protoAlias = plan.add(g.ProtoPackagePath, g.ProtoAlias, true)
	}

	for _, t := range g.Types {
		fieldMap := fieldMaps[t.Type.Name]
		// Named basic Go types (type Role string) are converted by name, so
		// their package must be imported; goimports drops it when unused.
		for _, f := range fieldMap.Fields() {
			if f.EntField == nil || f.EntField.Type == nil {
				continue
			}
			ti := f.EntField.Type
			if !f.EntField.HasGoType() || ti.PkgPath == "" {
				continue
			}
			preferred := ti.PkgName
			if preferred == "" {
				preferred = path.Base(ti.PkgPath)
			}
			plan.add(ti.PkgPath, preferred, ti.PkgPath != "time")
		}
		for _, f := range fieldMap.Enums() {
			if !f.IsEntEnum() {
				continue
			}
			enumPkg := g.entEnumPkgPath(t.Type.Name)
			plan.enumAliases[t.Type.Name] = plan.add(enumPkg, g.entEnumPreferredAlias(t.Type.Name), true)
		}
	}

	for _, t := range g.Types {
		fieldMap := fieldMaps[t.Type.Name]
		taken := make(map[string]struct{}, len(plan.used)+len(fieldMap)+4)
		for k := range plan.used {
			taken[k] = struct{}{}
		}
		taken["ent"] = struct{}{}
		taken["time"] = struct{}{}
		taken["nil"] = struct{}{}
		taken["true"] = struct{}{}
		taken["false"] = struct{}{}

		vars := make(map[string]string, len(fieldMap))
		for _, f := range fieldMap.Fields() {
			if f.EntField == nil {
				continue
			}
			base := f.EntField.BuilderField()
			name := base
			if _, used := taken[name]; used || token.Lookup(name).IsKeyword() {
				prefix := "field_" + base
				name = prefix
				for i := 2; ; i++ {
					if _, used := taken[name]; !used && !token.Lookup(name).IsKeyword() {
						break
					}
					name = fmt.Sprintf("%s%d", prefix, i)
				}
			}
			taken[name] = struct{}{}
			vars[f.EntField.Name] = name
		}
		plan.localVars[t.Type.Name] = vars
	}

	return plan, nil
}

// Imports returns the list of imports needed by the generated code.
func (g *Generator) Imports() ([]string, error) {
	plan, err := g.buildImportPlan()
	if err != nil {
		return nil, err
	}
	imp := make([]string, 0, len(plan.specs))
	for _, s := range plan.specs {
		if s.Alias == "" {
			imp = append(imp, fmt.Sprintf(`"%s"`, s.Path))
		} else {
			imp = append(imp, fmt.Sprintf(`%s "%s"`, s.Alias, s.Path))
		}
	}
	return imp, nil
}

// writeImportsFromPlan writes the import block from a resolved import plan.
func (g *Generator) writeImportsFromPlan(w io.Writer, plan *importPlan) error {
	if _, err := w.Write([]byte(generatedHeader + "\n")); err != nil {
		return err
	}
	if _, err := w.Write([]byte("package " + g.ConvPackage + "\n\n")); err != nil {
		return err
	}
	if _, err := w.Write([]byte("import (\n")); err != nil {
		return err
	}
	for _, s := range plan.specs {
		var line string
		if s.Alias == "" {
			line = fmt.Sprintf("\t%q\n", s.Path)
		} else {
			line = fmt.Sprintf("\t%s %q\n", s.Alias, s.Path)
		}
		if _, err := w.Write([]byte(line)); err != nil {
			return err
		}
	}
	if _, err := w.Write([]byte(")\n\n")); err != nil {
		return err
	}
	return nil
}

func (g *Generator) FieldMap(typeName string) (entproto.FieldMap, error) {
	return g.Adapter.FieldMap(typeName)
}

func (g *Generator) templateFuncs(plan *importPlan) template.FuncMap {
	return template.FuncMap{
		"ident":           g.ident,
		"entIdent":        g.entIdent,
		"entEnumAlias":    func(typeName string) string { return g.entEnumAlias(plan, typeName) },
		"newConverter":    g.newConverter,
		"toEntConv":       func(conv *converter.Converter, fld *gen.Field) string { return rewriteToEntConversion(plan, conv, fld) },
		"localVar":        func(typeName string, fld *gen.Field) string { return localFieldVar(plan, typeName, fld) },
		"pascal":          gen.Funcs["pascal"],
		"getFieldMap":     g.getFieldMap,
		"protoIdent":      func(ident string) string { return protoIdentForPlan(plan, ident) },
		"entPackageIdent": func(typeName string) string { return entPackageIdentForPlan(plan, typeName) },
		"pbEnumConst":     pbEnumConst,
		"entEnumConst":    entEnumConst,
	}
}

func rewriteToEntConversion(plan *importPlan, conv *converter.Converter, fld *gen.Field) string {
	expr := conv.ToEntConversion
	if expr == "" || fld == nil || !fld.HasGoType() || fld.Type.PkgPath == "" {
		return expr
	}
	alias := plan.byPath[fld.Type.PkgPath]
	if alias == "" {
		return expr
	}
	origPkg := fld.Type.PkgName
	if origPkg == "" {
		origPkg = path.Base(fld.Type.PkgPath)
	}
	if alias == origPkg {
		return expr
	}
	prefix := ""
	rest := expr
	for strings.HasPrefix(rest, "[]") || strings.HasPrefix(rest, "*") {
		if strings.HasPrefix(rest, "[]") {
			prefix += "[]"
			rest = rest[2:]
		} else {
			prefix += "*"
			rest = rest[1:]
		}
	}
	if after, ok := strings.CutPrefix(rest, origPkg+"."); ok {
		return prefix + alias + "." + after
	}
	return expr
}

func localFieldVar(plan *importPlan, typeName string, fld *gen.Field) string {
	if fld == nil {
		return ""
	}
	if vars := plan.localVars[typeName]; vars != nil {
		if v, ok := vars[fld.Name]; ok {
			return v
		}
	}
	return fld.BuilderField()
}

// pbEnumConst resolves the protoc-gen-go constant name for an ent enum value
// using the real protobuf descriptor and the entproto.Enum annotation number.
func pbEnumConst(mapping *entproto.FieldMappingDescriptor, value string) (string, error) {
	return mapping.PbEnumValueConstName(value)
}

// entEnumConst returns the ent constant name for an enum value, delegating to
// ent's own naming rule (Field.EnumName).
func entEnumConst(field *gen.Field, value string) string {
	return field.EnumName(value)
}

func (g *Generator) ident(qualifiedIdent string) string {
	return qualifiedIdent
}

func (g *Generator) getFieldMap(typeName string) (entproto.FieldMap, error) {
	return g.Adapter.FieldMap(typeName)
}

func (g *Generator) entIdent(pkgAlias, ident string) string {
	if pkgAlias == "" {
		return "ent." + ident
	}
	return pkgAlias + "." + ident
}

func protoIdentForPlan(plan *importPlan, ident string) string {
	if plan.protoAlias != "" {
		return plan.protoAlias + "." + ident
	}
	return ident
}

func entPackageIdentForPlan(plan *importPlan, typeName string) string {
	if plan.entAlias != "" {
		return plan.entAlias + "." + typeName
	}
	return "ent." + typeName
}

func (g *Generator) entEnumPkgPath(typeName string) string {
	if node, ok := g.nodeIndex[typeName]; ok {
		return path.Join(g.EntPackage, node.PackageDir())
	}
	return g.EntPackage
}

func (g *Generator) entEnumPreferredAlias(typeName string) string {
	if node, ok := g.nodeIndex[typeName]; ok {
		return node.Package()
	}
	return "ent"
}

func (g *Generator) entEnumAlias(plan *importPlan, typeName string) string {
	if alias := plan.enumAliases[typeName]; alias != "" {
		return alias
	}
	return g.entEnumPreferredAlias(typeName)
}

func (g *Generator) newConverter(fld *entproto.FieldMappingDescriptor, typeName string) (*converter.Converter, error) {
	if _, ok := g.typeIndex[typeName]; !ok {
		return nil, fmt.Errorf("type %q not found", typeName)
	}
	return converter.NewConverter(fld, typeName)
}
