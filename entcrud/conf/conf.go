package conf

import (
	"github.com/go-sphere/entc-extensions/entcrud/internal/inspect"
)

// FilesConf describes one generated bind package for
// [github.com/go-sphere/entc-extensions/entcrud.BindFiles]. Create it with
// [NewFilesConf], which enables StrictTypeCheck; a zero FilesConf has strict
// checking off and no Dir, which BindFiles rejects.
type FilesConf struct {
	// Dir is the output directory, created if missing. Required; a relative
	// path is resolved against the working directory, and a symlink is
	// rejected.
	Dir string
	// Package is the Go package name of the generated files. Empty means
	// "bind".
	Package string
	// RemoveBeforeGenerate deletes every .go file directly in Dir that starts
	// with "// Code generated by Sphere. DO NOT EDIT." before writing, so
	// files for removed entities disappear. Other files are kept.
	RemoveBeforeGenerate bool
	// StrictTypeCheck makes incompatible field pairs fail generation with a
	// [*TypeMismatchListError]. When false, such fields are silently left out
	// of the generated functions.
	StrictTypeCheck bool
	// ExtraImports are added to every entity file. Imports for Target, the
	// ent field-constant package, and custom converters are added
	// automatically, so this is rarely needed. The element type is internal
	// to this module.
	ExtraImports []inspect.Import
	// Entities lists the entities to generate, in output order.
	Entities []*EntityConf
}

// NewFilesConf returns a FilesConf for dir and package pkg containing
// entities, with StrictTypeCheck enabled and RemoveBeforeGenerate disabled.
// Use [FilesConf.Apply] for further file-level options.
func NewFilesConf(dir string, pkg string, entities ...*EntityConf) *FilesConf {
	return &FilesConf{
		Dir:                  dir,
		Package:              pkg,
		RemoveBeforeGenerate: false,
		StrictTypeCheck:      true,
		ExtraImports:         nil,
		Entities:             entities,
	}
}

// FilesOption modifies a [FilesConf]; see [FilesConf.Apply].
type FilesOption func(*FilesConf)

// Apply applies opts to c in order, ignoring nil options, and returns c for
// chaining.
func (c *FilesConf) Apply(opts ...FilesOption) *FilesConf {
	for _, opt := range opts {
		if opt != nil {
			opt(c)
		}
	}
	return c
}

// WithStrictTypeCheck sets [FilesConf.StrictTypeCheck]. [NewFilesConf]
// defaults it to true.
func WithStrictTypeCheck(strict bool) FilesOption {
	return func(c *FilesConf) {
		c.StrictTypeCheck = strict
	}
}

// EntityConf describes the bind functions generated for one ent entity.
type EntityConf struct {
	// Source is a value of the ent entity struct, such as ent.User{} (a
	// pointer is also accepted). Its struct fields decide which protobuf
	// fields are bound, and its type name names the output file. Required.
	Source any
	// Target is a value of the protobuf message struct, such as
	// entpb.User{} (a pointer is also accepted). Required.
	Target any
	// Actions are values of ent builder types, such as ent.UserCreate{} and
	// ent.UserUpdateOne{}; one function is generated per action. An entity
	// with no actions produces no file.
	Actions []any
	// IgnoreFields lists snake_case field names (for example "users" or the
	// value of user.FieldName) excluded from generation; matching is
	// case-insensitive.
	IgnoreFields []string
	// CustomFieldConverters maps a snake_case field name to a converter
	// function; see [WithCustomFieldConverter].
	CustomFieldConverters map[string]any
}

// NewEntity returns an EntityConf for source, target, and actions with opts
// applied in order. Package names and import paths are derived from the
// values' types by reflection.
func NewEntity(source, target any, actions []any, opts ...Option) *EntityConf {
	ctx := &EntityConf{
		Source:                source,
		Target:                target,
		Actions:               actions,
		IgnoreFields:          nil,
		CustomFieldConverters: nil,
	}
	for _, opt := range opts {
		opt(ctx)
	}
	return ctx
}

// Option modifies an [EntityConf]; see [NewEntity].
type Option func(*EntityConf)

// WithIgnoreFields sets [EntityConf.IgnoreFields], replacing any list set by
// an earlier WithIgnoreFields.
func WithIgnoreFields(fields ...string) Option {
	return func(c *EntityConf) {
		c.IgnoreFields = fields
	}
}

// WithCustomFieldConverter makes the generated code pass the protobuf value of
// field through converter before calling the ent setter. field is the
// snake_case ent field name, normally the ent field constant such as
// user.FieldBirthday; a later call for the same field wins.
//
// converter must be an exported top-level function (not a closure or method)
// with one parameter that accepts the protobuf field value (the pointed-to
// value for pointer fields) and one result assignable to the setter argument,
// for example func(int64) time.Time. Its package is imported by the generated
// file. An invalid converter is reported as a type mismatch under
// [FilesConf.StrictTypeCheck] and otherwise causes the field to be skipped.
func WithCustomFieldConverter(field string, converter any) Option {
	return func(c *EntityConf) {
		if c.CustomFieldConverters == nil {
			c.CustomFieldConverters = make(map[string]any)
		}
		c.CustomFieldConverters[field] = converter
	}
}
